"""Load and validate report definition YAML into ReportDef dataclasses
(M2 row 3: the parse half).

Report definitions are identified by UUID (not name): the content-zip
import path requires a stable id so re-imports update in place. This
module never writes to its input: a YAML with no ``id`` is handed to the
optional ``on_missing_id(path) -> str`` callback (the factory wrapper,
``vcfcf_reports.loader``, mints a uuid4 into the file, same contract as
views and dashboards); with no callback it is a ``ReportValidationError``.

View and dashboard name references resolve against the ``views_dir`` and
``dashboards_dir`` a caller passes; both are required here. The factory
wrapper keeps the old ``content/views`` / ``content/dashboards`` /
``content/reports`` defaults.

YAML schema (see .claude/agents/report-author.md for the canonical spec):

    name: "[VCF Content Factory] My Report"
    description: "What this report shows"
    id: <auto-generated UUID on first validate>

    subject_types:
      - adapter_kind: VMWARE
        resource_kind: VirtualMachine
        type: self              # self | descendant
        # filter: optional metric filter JSON (advanced)

    sections:
      - type: CoverPage
      - type: TableOfContents
      - type: View
        view: "<exact view name>"     # resolved to UUID by loader
        orientation: Landscape        # Landscape | Portrait
        colorize: true                # colorize list view rows
      - type: Dashboard
        dashboard: "<exact dashboard name>"
        orientation: Landscape

    settings:
      show_page_footer: true
      output_formats:
        - pdf
        - csv

Cross-reference resolution:
  - View names are resolved by scanning views/ (or a configurable dir).
  - Dashboard names are resolved by scanning dashboards/.
  - Resolution happens at load time so validation catches broken refs.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, List, Optional

import yaml
import yaml.constructor
import yaml.resolver


def _strict_load(stream):
    """yaml.safe_load replacement that raises on duplicate mapping keys."""
    class _StrictKeyLoader(yaml.SafeLoader):
        pass

    def _no_duplicates(loader, node, deep=False):
        mapping = {}
        for key_node, value_node in node.value:
            key = loader.construct_object(key_node, deep=deep)
            if key in mapping:
                raise yaml.constructor.ConstructorError(
                    None, None,
                    f"duplicate key '{key}' found at {key_node.start_mark}",
                    key_node.start_mark,
                )
            mapping[key] = loader.construct_object(value_node, deep=deep)
        return mapping

    _StrictKeyLoader.add_constructor(
        yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG,
        _no_duplicates,
    )
    return yaml.load(stream, Loader=_StrictKeyLoader)



class ReportValidationError(ValueError):
    pass


_UUID_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
)
_HEX6_RE = re.compile(r"^[0-9A-Fa-f]{6}$")

# Supported section types.
SECTION_TYPES = {"CoverPage", "TableOfContents", "View", "Dashboard"}

# Fixed ContentKey values for the static section types.
_STATIC_CONTENT_KEYS = {
    "CoverPage": "COVER_PAGE",
    "TableOfContents": "TABLE_OF_CONTENTS",
}

VALID_ORIENTATIONS = {"Landscape", "Portrait"}
VALID_OUTPUT_FORMATS = {"pdf", "csv"}

#: Oldest VCF Operations version whose own built-in export shows each section
#: ``omit:`` entry's element absent (content.xml of the 8.18.7, 9.0.2 and
#: 9.1.1 report exports; template_fidelity_wire_format.md §Omit version
#: floor). A Tier 2 pak build fails on an entry whose floor is above its
#: oldest supported line.
SECTION_OMIT_MIN_OPS_VERSION = {
    "formatting": (8, 18, 7),  # 77 of 91 8.18.7 View sections carry no ContentFormatting
}
OLDEST_OMIT_EVIDENCE = (8, 18, 7)


@dataclass
class SubjectType:
    adapter_kind: str
    resource_kind: str
    type: str            # "self" or "descendant"
    filter: str = ""     # optional HTML-entity-encoded JSON filter


@dataclass
class Section:
    type: str            # CoverPage | TableOfContents | View | Dashboard
    # View sections
    view_name: str = ""   # author-written view name; resolved to UUID at render
    view_id: str = ""     # filled during load
    orientation: str = "Landscape"
    colorize: bool = True
    # Dashboard sections
    dashboard_name: str = ""
    dashboard_id: str = ""
    # Fidelity (wire-formats/template_fidelity_wire_format.md). external: the section names
    # a product-shipped (or other-pak) view or dashboard by raw id
    # (view_id: / dashboard_id:), never bundled. font_color / cover_colorize:
    # CoverPage ContentFormatting. omit_formatting: a View section without
    # ContentFormatting (most built-in View sections).
    external: bool = False
    font_color: Optional[str] = None
    cover_colorize: Optional[bool] = None
    omit_formatting: bool = False


@dataclass
class ReportSettings:
    show_page_footer: bool = True
    output_formats: List[str] = field(default_factory=lambda: ["pdf"])


@dataclass
class ReportDef:
    name: str
    description: str
    subject_types: List[SubjectType]
    sections: List[Section]
    settings: ReportSettings
    id: str = ""
    source_path: Optional[Path] = None
    released: bool = False   # publish gate
    version: str = "1.0.0"  # internal semver
    # `subject_types: []` written explicitly: a report with no SubjectType
    # (five third-party templates). An absent key is still an error.
    no_subject_types: bool = False

    def validate(self, enforce_framework_prefix: bool = True) -> None:
        if not self.name.strip():
            raise ReportValidationError("name is required")
        if enforce_framework_prefix and not self.name.startswith("[VCF Content Factory] "):
            src = str(self.source_path) if self.source_path else self.name
            raise ReportValidationError(
                f'{src}: name "{self.name}" missing framework prefix '
                f'"[VCF Content Factory]". All factory-authored content must carry the literal '
                f'"[VCF Content Factory]" prefix (see CLAUDE.md §Hard rules #5). For third-party '
                f"bundle content, ensure the bundle manifest sets factory_native: false."
            )
        if not self.subject_types:
            if not self.no_subject_types:
                raise ReportValidationError(
                    f"{self.name}: at least one subject_type is required "
                    f"(or subject_types: [] for a report with no SubjectType)"
                )
        for st in self.subject_types:
            if not st.adapter_kind:
                raise ReportValidationError(
                    f"{self.name}: subject_type missing adapter_kind"
                )
            if not st.resource_kind:
                raise ReportValidationError(
                    f"{self.name}: subject_type missing resource_kind"
                )
            if st.type not in ("self", "descendant"):
                raise ReportValidationError(
                    f"{self.name}: subject_type.type must be 'self' or 'descendant'; "
                    f"got {st.type!r}"
                )
        if not self.sections:
            raise ReportValidationError(
                f"{self.name}: at least one section is required"
            )
        for sec in self.sections:
            if sec.type not in SECTION_TYPES:
                raise ReportValidationError(
                    f"{self.name}: section type must be one of "
                    f"{sorted(SECTION_TYPES)}; got {sec.type!r}"
                )
            if (sec.font_color is not None or sec.cover_colorize is not None) and sec.type != "CoverPage":
                raise ReportValidationError(
                    f"{self.name}: font_color and CoverPage colorize are only rendered "
                    f"on a CoverPage section"
                )
            if sec.omit_formatting and sec.type != "View":
                raise ReportValidationError(f"{self.name}: omit formatting applies to View sections only")
            if sec.type == "View":
                if not sec.view_name and not sec.external:
                    raise ReportValidationError(
                        f"{self.name}: View section missing 'view' name"
                    )
                if not sec.view_id:
                    raise ReportValidationError(
                        f"{self.name}: View section '{sec.view_name}' could not "
                        f"be resolved — ensure the view exists in views/"
                    )
                if sec.orientation not in VALID_ORIENTATIONS:
                    raise ReportValidationError(
                        f"{self.name}: View section orientation must be one of "
                        f"{sorted(VALID_ORIENTATIONS)}; got {sec.orientation!r}"
                    )
            if sec.type == "Dashboard":
                if not sec.dashboard_name and not sec.external:
                    raise ReportValidationError(
                        f"{self.name}: Dashboard section missing 'dashboard' name"
                    )
                if not sec.dashboard_id:
                    raise ReportValidationError(
                        f"{self.name}: Dashboard section '{sec.dashboard_name}' "
                        f"could not be resolved — ensure the dashboard exists in "
                        f"dashboards/"
                    )
                if sec.orientation not in VALID_ORIENTATIONS:
                    raise ReportValidationError(
                        f"{self.name}: Dashboard section orientation must be one of "
                        f"{sorted(VALID_ORIENTATIONS)}; got {sec.orientation!r}"
                    )
        for fmt in self.settings.output_formats:
            if fmt not in VALID_OUTPUT_FORMATS:
                raise ReportValidationError(
                    f"{self.name}: output_format must be one of "
                    f"{sorted(VALID_OUTPUT_FORMATS)}; got {fmt!r}"
                )


    def omit_version_problems(self, target_version=None) -> List[str]:
        """Section ``omit:`` entries whose floor (SECTION_OMIT_MIN_OPS_VERSION)
        is above ``target_version``; with no target, above the oldest export
        read (OLDEST_OMIT_EVIDENCE) or unknown."""
        target = _version_tuple(target_version) if target_version is not None else OLDEST_OMIT_EVIDENCE
        out: List[str] = []
        for i, sec in enumerate(self.sections):
            if not sec.omit_formatting:
                continue
            floor = SECTION_OMIT_MIN_OPS_VERSION.get("formatting")
            if floor is not None and _version_tuple(floor) <= target:
                continue
            seen = (f"absent only from VCF Operations {'.'.join(map(str, floor))} and later exports"
                    if floor is not None else "absent from no product export")
            out.append(
                f"{self.source_path or self.name}: report {self.name!r}: sections[{i}]: "
                f"omit: formatting leaves out an element {seen}; whether VCF Operations "
                f"{'.'.join(map(str, target))} imports the report without it is unproven"
            )
        return out

    def external_references(self) -> List[tuple]:
        """``(content_type, id, where)`` for each section that names a view
        or dashboard by raw id (``view_id:`` / ``dashboard_id:``), for the
        stock-id baseline check (template_fidelity_wire_format.md)."""
        out: List[tuple] = []
        for i, sec in enumerate(self.sections):
            if not sec.external:
                continue
            where = f"{self.source_path or self.name}: report {self.name!r}: sections[{i}]"
            if sec.type == "View" and sec.view_id:
                out.append(("view", sec.view_id, f"{where} view_id"))
            elif sec.type == "Dashboard" and sec.dashboard_id:
                out.append(("dashboard", sec.dashboard_id, f"{where} dashboard_id"))
        return out


def _version_tuple(v) -> tuple:
    parts = [int(x) for x in (v if isinstance(v, tuple) else str(v).split("."))]
    while len(parts) > 1 and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


IdMinter = Callable[[Path], str]


def _resolve_id(path: Path, data: dict, on_missing_id: Optional[IdMinter]) -> str:
    """The report's ``id`` from ``data``, validated as a uuid4.

    A missing ``id`` is handed to ``on_missing_id`` (the factory mints one
    into the file and returns it); with no callback it is an error, because
    this module never writes to its input. The callback's return gets the
    same normalize-and-validate path as a YAML id.
    """
    report_id = str(data.get("id", "") or "").strip().lower()
    source = "id"
    if not report_id:
        if on_missing_id is None:
            raise ReportValidationError(
                f"{path}: missing id (a uuid4); pass on_missing_id= to mint one"
            )
        report_id = str(on_missing_id(path) or "").strip().lower()
        source = f"on_missing_id ({getattr(on_missing_id, '__name__', on_missing_id)!s})"
    if not _UUID_RE.match(report_id):
        if source == "id":
            raise ReportValidationError(
                f"{path}: id '{report_id}' is not a valid uuid4"
            )
        raise ReportValidationError(
            f"{path}: {source} gave '{report_id}', which is not a valid uuid4"
        )
    return report_id


def _build_view_index(views_dir: Path) -> dict[str, str]:
    """Return {view_name: view_id} by scanning views_dir for YAML files."""
    index: dict[str, str] = {}
    if not views_dir.exists():
        return index
    for p in sorted(views_dir.rglob("*.y*ml")):
        try:
            data = yaml.safe_load(p.read_text()) or {}
            vname = str(data.get("name", "")).strip()
            vid = str(data.get("id", "") or "").strip().lower()
            if vname and vid and _UUID_RE.match(vid):
                index[vname] = vid
        except Exception:
            pass  # non-fatal; will surface as unresolved view at validate
    return index


def _build_dashboard_index(dashboards_dir: Path) -> dict[str, str]:
    """Return {dashboard_name: dashboard_id} by scanning dashboards_dir."""
    index: dict[str, str] = {}
    if not dashboards_dir.exists():
        return index
    for p in sorted(dashboards_dir.rglob("*.y*ml")):
        try:
            data = yaml.safe_load(p.read_text()) or {}
            dname = str(data.get("name", "")).strip()
            did = str(data.get("id", "") or "").strip().lower()
            if dname and did and _UUID_RE.match(did):
                index[dname] = did
        except Exception:
            pass
    return index


def load_file(
    path: str | Path,
    views_dir: str | Path,
    dashboards_dir: str | Path,
    enforce_framework_prefix: bool = True,
    *,
    on_missing_id: Optional[IdMinter] = None,
) -> "ReportDef":
    """Load and validate a single report definition YAML file.

    Resolves view and dashboard name references to UUIDs by scanning the
    respective directories. A missing ``id`` goes to ``on_missing_id`` (see
    the module docstring); nothing is written here.

    Args:
        path:           Path to the report YAML file.
        views_dir:      Directory containing view definition YAMLs.
        dashboards_dir: Directory containing dashboard definition YAMLs.
        on_missing_id:  Callback minting an id for a YAML that has none.

    Returns:
        A validated ReportDef.

    Raises:
        ReportValidationError: if the YAML is invalid or a cross-reference
            cannot be resolved.
    """
    path = Path(path)
    views_dir = Path(views_dir)
    dashboards_dir = Path(dashboards_dir)

    try:
        data = _strict_load(path.read_text()) or {}
    except yaml.constructor.ConstructorError as exc:
        raise ReportValidationError(f"{path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ReportValidationError(f"{path}: expected a YAML mapping")

    report_id = _resolve_id(path, data, on_missing_id)

    name = str(data.get("name", "")).strip()
    description = str(data.get("description", "") or "").strip()

    # subject_types
    subject_types: List[SubjectType] = []
    for raw_st in (data.get("subject_types") or []):
        subject_types.append(SubjectType(
            adapter_kind=str(raw_st.get("adapter_kind", "")).strip(),
            resource_kind=str(raw_st.get("resource_kind", "")).strip(),
            type=str(raw_st.get("type", "self")).strip().lower(),
            filter=str(raw_st.get("filter", "") or "").strip(),
        ))

    # Build view and dashboard indexes for cross-reference resolution
    view_index = _build_view_index(views_dir)
    dashboard_index = _build_dashboard_index(dashboards_dir)

    # sections
    sections: List[Section] = []
    for i, raw_sec in enumerate(data.get("sections") or []):
        sec_type = str(raw_sec.get("type", "")).strip()
        where = f"{path}: report {str(data.get('name', '')).strip()!r}: sections[{i}]"
        raw_omit = raw_sec.get("omit") or []
        if raw_omit not in ([], ["formatting"]):
            raise ReportValidationError(f"{where}: omit accepts only [formatting]; got {raw_omit!r}")
        omit_formatting = raw_omit == ["formatting"]

        if sec_type in ("CoverPage", "TableOfContents"):
            sec = Section(type=sec_type)
            if "font_color" in raw_sec:
                fc = raw_sec["font_color"]
                if not isinstance(fc, str) or not _HEX6_RE.match(fc):
                    raise ReportValidationError(f"{where}: font_color must be six hex digits, quoted; got {fc!r}")
                sec.font_color = fc
            if "colorize" in raw_sec:
                if not isinstance(raw_sec["colorize"], bool):
                    raise ReportValidationError(f"{where}: colorize must be a bool")
                sec.cover_colorize = raw_sec["colorize"]
            sec.omit_formatting = omit_formatting
            sections.append(sec)

        elif sec_type in ("View", "Dashboard"):
            key, id_key = ("view", "view_id") if sec_type == "View" else ("dashboard", "dashboard_id")
            index = view_index if sec_type == "View" else dashboard_index
            if key in raw_sec and id_key in raw_sec:
                raise ReportValidationError(
                    f"{where}: a {sec_type} section sets exactly one of '{key}' (the "
                    f"project's own {key}, by exact name) or '{id_key}' (a product-shipped "
                    f"or other-pak {key}, by raw id)"
                )
            orientation = str(raw_sec.get("orientation", "Landscape") or "Landscape").strip()
            external = id_key in raw_sec
            if external:
                ref_name = ""
                ref_id = str(raw_sec[id_key] or "").strip().lower()
                if not _UUID_RE.match(ref_id):
                    raise ReportValidationError(f"{where}: {id_key} must be a UUID; got {raw_sec[id_key]!r}")
                own = [n for n, v in index.items() if v == ref_id]
                if own:
                    raise ReportValidationError(
                        f"{where}: {id_key} {ref_id} is this project's own {key} {own[0]!r}; "
                        f"reference it by name ({key}: \"{own[0]}\") so it is bundled"
                    )
            else:
                ref_name = str(raw_sec.get(key, "") or "").strip()
                ref_id = index.get(ref_name, "")
            if sec_type == "View":
                colorize_raw = raw_sec.get("colorize", True)
                colorize = bool(colorize_raw) if not isinstance(colorize_raw, bool) else colorize_raw
                if omit_formatting and "colorize" in raw_sec:
                    raise ReportValidationError(f"{where}: omit formatting contradicts colorize")
                sections.append(Section(
                    type="View", view_name=ref_name, view_id=ref_id, orientation=orientation,
                    colorize=colorize, external=external, omit_formatting=omit_formatting,
                ))
            else:
                if "colorize" in raw_sec:
                    raise ReportValidationError(f"{where}: colorize is not rendered on a Dashboard section")
                sections.append(Section(
                    type="Dashboard", dashboard_name=ref_name, dashboard_id=ref_id,
                    orientation=orientation, external=external, omit_formatting=omit_formatting,
                ))

        else:
            # Unknown section types are preserved so validate() can report them
            sections.append(Section(type=sec_type))

    # settings
    raw_settings = data.get("settings") or {}
    show_page_footer = bool(raw_settings.get("show_page_footer", True))
    raw_formats = raw_settings.get("output_formats") or ["pdf"]
    output_formats = [str(f).strip().lower() for f in raw_formats]
    settings = ReportSettings(
        show_page_footer=show_page_footer,
        output_formats=output_formats,
    )

    released_raw = data.get("released", False)
    released = bool(released_raw) if isinstance(released_raw, bool) else False
    version = str(data.get("version", "1.0.0") or "1.0.0").strip() or "1.0.0"

    raw_st = data.get("subject_types")
    rd = ReportDef(
        no_subject_types=isinstance(raw_st, list) and raw_st == [],
        id=report_id,
        name=name,
        description=description,
        subject_types=subject_types,
        sections=sections,
        settings=settings,
        source_path=path,
        released=released,
        version=version,
    )
    try:
        rd.validate(enforce_framework_prefix=enforce_framework_prefix)
    except ReportValidationError as exc:
        # Field errors name the report; prefix the file so every message
        # names both (some already start with the path).
        if str(exc).startswith(str(path)):
            raise
        raise ReportValidationError(f"{path}: {exc}") from None
    import warnings
    for _problem in rd.omit_version_problems():
        warnings.warn(_problem, UserWarning, stacklevel=2)
    return rd


def load_dir(
    directory: str | Path,
    views_dir: str | Path,
    dashboards_dir: str | Path,
    enforce_framework_prefix: bool = True,
    *,
    on_missing_id: Optional[IdMinter] = None,
) -> List[ReportDef]:
    """Load all report definition YAML files from a directory.

    Checks for duplicate names across the directory and raises
    ReportValidationError if any are found.
    """
    directory = Path(directory)
    if not directory.exists():
        return []
    out: List[ReportDef] = []
    seen: dict[str, Path] = {}
    for p in sorted(directory.rglob("*.y*ml")):
        rd = load_file(
            p, views_dir=views_dir, dashboards_dir=dashboards_dir,
            enforce_framework_prefix=enforce_framework_prefix, on_missing_id=on_missing_id,
        )
        if rd.name in seen:
            raise ReportValidationError(
                f"duplicate report name '{rd.name}' "
                f"in {p} and {seen[rd.name]}"
            )
        seen[rd.name] = p
        out.append(rd)
    return out
